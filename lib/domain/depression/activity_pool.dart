      ActivityCategory.socialConnection => 'Social',
      ActivityCategory.creative => 'Creative',
      ActivityCategory.selfCare => 'Self-Care',
      ActivityCategory.productive => 'Productive',
      ActivityCategory.leisure => 'Leisure',
      ActivityCategory.routine => 'Routine',
