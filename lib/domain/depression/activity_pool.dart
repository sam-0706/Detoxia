    ActivityCategory.physicalActivity => const IconData(0xe3ac, fontFamily: 'MaterialIcons'), // directions_run
    ActivityCategory.socialConnection => const IconData(0xe491, fontFamily: 'MaterialIcons'), // people
    ActivityCategory.creative => const IconData(0xe3ae, fontFamily: 'MaterialIcons'), // palette
    ActivityCategory.selfCare => const IconData(0xf0504, fontFamily: 'MaterialIcons'), // spa
    ActivityCategory.productive => const IconData(0xe179, fontFamily: 'MaterialIcons'), // checklist
    ActivityCategory.leisure => const IconData(0xe1bd, fontFamily: 'MaterialIcons'), // local_cafe
    ActivityCategory.routine => const IconData(0xe616, fontFamily: 'MaterialIcons'), // schedule
